"""Generate engine-neutral attribute contracts from the authoring JSON source."""
from pathlib import Path
import argparse
import json
import subprocess

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'schemas/authoring/npr-attributes.v1.json'
DEST = ROOT / 'crates/bevy-stylized-gltf/src/contract.rs'


def generated():
    spec=json.loads(SOURCE.read_text())
    source='''//! Generated by tools/checks/generate_attributes.py; do not edit by hand.
/// A fallback value in the portable vertex attribute contract.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum NprAttributeDefault { /// Scalar fallback.
Scalar(f32), /// Three-component fallback.
Vec3([f32; 3]) }
/// Engine-neutral vertex attribute specification.
#[derive(Clone, Copy, Debug)]
pub struct NprAttributeSpec {
/// Authored glTF semantic.
pub authored_semantic: &'static str,
/// Loader key without leading underscore.
pub loader_key: &'static str,
/// Blender domain.
pub blender_domain: &'static str,
/// Blender data type.
pub blender_data_type: &'static str,
/// Portable vertex format identifier.
pub vertex_format: &'static str,
/// Fallback value.
pub default: NprAttributeDefault,
/// Meaning of missing attribute.
pub missing_fallback: &'static str,
}
'''
    source+=f'/// All authored NPR attributes.\npub const NPR_ATTRIBUTE_SPECS: [NprAttributeSpec; {len(spec["attributes"])}] = [\n'
    q=json.dumps
    for a in spec['attributes']:
        d=a['default'];default=f'NprAttributeDefault::Vec3({d!r})' if isinstance(d,list) else f'NprAttributeDefault::Scalar({float(d)})'
        source+='NprAttributeSpec {'+','.join(f'{k}: {q(v)}' for k,v in {'authored_semantic':a['name'],'loader_key':a['name'][1:],'blender_domain':a['domain'],'blender_data_type':a['data_type'],'vertex_format':a['bevy_vertex_format'],'missing_fallback':a['missing_fallback']}.items())+f', default: {default}'+ '},\n'
    source+='];\n'
    return subprocess.run(['rustfmt','--edition','2024'],input=source,text=True,capture_output=True,check=True).stdout


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    value=generated()
    if args.check:
        if not DEST.is_file() or DEST.read_text()!=value:raise SystemExit('attribute contract is stale; run generator')
    else:DEST.write_text(value)
